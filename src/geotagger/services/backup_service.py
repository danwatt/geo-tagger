"""Compact JSON export of user-authored data — the parts nothing else can
regenerate: place names/bounds, person names/families, face-to-person
labels/ignores/negatives, per-photo lat/lng, and runtime settings.

Deliberately skipped (all derived, and each expensive to re-serialize):
reverse-geocode results (photos.loc_*, geocode_cache — regenerated by
geocode.py against the offline datasets), face embeddings
(face_embeddings — regenerated by rerunning face detection), photo scan
metadata (size/mtime/checksum/etc — rebuilt by a rescan), and
dataset_downloads (just download-history bookkeeping). lat/lng are included
even though they're also mirrored to XMP sidecars per the immutable-originals
rule — a sidecar can go missing or be edited outside the app, so the DB's
copy is still worth a backup.

Faces/places/geotags are anchored to (dir, filename) rather than the DB's
internal photo id, which isn't stable across a fresh scan. Faces have no
natural key of their own, so face_negatives references a face by its position
in the exported `faces` list.
"""

import time

from geotagger import index

BACKUP_VERSION = 1


def build_backup() -> dict:
    """Assemble the backup dict. Runs several small queries — cheap even on a
    large library, since nothing here touches the photos/embeddings tables."""
    db = index.get_db()

    families_rows = db.execute("SELECT id, name, created_at FROM families ORDER BY id").fetchall()
    family_names = {r["id"]: r["name"] for r in families_rows}

    persons_rows = db.execute(
        "SELECT id, name, birth_date, not_before, not_after, family_id, created_at "
        "FROM persons ORDER BY id"
    ).fetchall()
    person_names = {r["id"]: r["name"] for r in persons_rows}

    photo_rows = db.execute(
        "SELECT id, dir, filename, lat, lng, geotag_source FROM photos"
    ).fetchall()
    photos_by_id = {r["id"]: (r["dir"], r["filename"]) for r in photo_rows}
    geotags = [
        {
            "dir": r["dir"], "filename": r["filename"],
            "lat": r["lat"], "lng": r["lng"], "geotag_source": r["geotag_source"],
        }
        for r in photo_rows
        if r["lat"] is not None and r["lng"] is not None
    ]

    places = []
    for r in db.execute(
        "SELECT name, type, bounds, created_at, representative_photo_id FROM places ORDER BY id"
    ):
        rep = photos_by_id.get(r["representative_photo_id"])
        places.append({
            "name": r["name"], "type": r["type"], "bounds": r["bounds"],
            "created_at": r["created_at"],
            "representative_photo": {"dir": rep[0], "filename": rep[1]} if rep else None,
        })

    faces = []
    face_index_by_id: dict[int, int] = {}
    for r in db.execute(
        "SELECT id, photo_id, person_id, bbox, det_score, source, ignored, come_back, "
        "representative, created_at, assigned_at, ignored_at, come_back_at "
        "FROM faces ORDER BY id"
    ):
        photo = photos_by_id.get(r["photo_id"])
        if not photo:
            continue  # orphaned row (photo since pruned) — nothing to anchor it to
        face_index_by_id[r["id"]] = len(faces)
        faces.append({
            "photo_dir": photo[0], "photo_filename": photo[1],
            "bbox": r["bbox"], "det_score": r["det_score"], "source": r["source"],
            "ignored": bool(r["ignored"]), "come_back": bool(r["come_back"]),
            "representative": bool(r["representative"]),
            "person": person_names.get(r["person_id"]),
            "created_at": r["created_at"], "assigned_at": r["assigned_at"],
            "ignored_at": r["ignored_at"], "come_back_at": r["come_back_at"],
        })

    negatives = []
    for r in db.execute("SELECT face_id, person_id, created_at FROM face_negatives"):
        face_idx = face_index_by_id.get(r["face_id"])
        person = person_names.get(r["person_id"])
        if face_idx is None or person is None:
            continue
        negatives.append({"face": face_idx, "person": person, "created_at": r["created_at"]})

    return {
        "version": BACKUP_VERSION,
        "exported_at": time.time(),
        "settings": index.get_all_settings(),
        "families": [{"name": r["name"], "created_at": r["created_at"]} for r in families_rows],
        "persons": [
            {
                "name": r["name"], "birth_date": r["birth_date"],
                "not_before": r["not_before"], "not_after": r["not_after"],
                "family": family_names.get(r["family_id"]),
                "created_at": r["created_at"],
            }
            for r in persons_rows
        ],
        "places": places,
        "geotags": geotags,
        "faces": faces,
        "face_negatives": negatives,
    }
